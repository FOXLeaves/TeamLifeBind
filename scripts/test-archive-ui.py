"""Run all new interface families in a separate real 26.3 client.

Usage: python scripts/test-archive-ui.py fabric [forge neoforge]
Requires Java 26 and a graphical session. No world or external server is opened.
"""
from pathlib import Path
import hashlib
import json
import os
import struct
import subprocess
import sys
import time
import shutil

ROOT = Path(__file__).resolve().parents[1]
motion_only = '--motion-only' in sys.argv
title_only = '--title-only' in sys.argv
render_mode=next((arg.split('=',1)[1] for arg in sys.argv[1:] if arg.startswith('--render-mods=')),'')
options_only='--render-options-only' in sys.argv
if options_only and not render_mode:raise SystemExit('--render-options-only requires --render-mods')
if render_mode not in ('','sodium','iris'):raise SystemExit('Choose --render-mods=sodium or --render-mods=iris')
if title_only and (motion_only or render_mode):raise SystemExit('--title-only runs the three title layouts and motion on the native renderer')
platforms = [arg for arg in sys.argv[1:] if arg not in ('--motion-only','--render-options-only','--title-only') and not arg.startswith('--render-mods=')] or (["fabric","neoforge"] if render_mode else ["fabric", "forge", "neoforge"])
kinds = ("title","pause","options","video","online","sound","mouse","controls","keybinds","accessibility","chat-options","skin","language","worlds","servers","create-game","create-world","create-more","confirm","book","widgets","widgets-reload","chest27","chest54","hopper","dispenser","magic","loading")
if options_only:kinds=('title','options','video')
if title_only:kinds=('title',)
if render_mode=='iris':kinds=(*kinds,'iris-options')
case_count = 1 if motion_only else len(kinds) * 3
if not set(platforms) <= {"fabric", "forge", "neoforge"}:
    raise SystemExit("Choose fabric, forge, neoforge")
env = dict(os.environ)
if title_only:env['JAVA_TOOL_OPTIONS']=env.get('JAVA_TOOL_OPTIONS','')+' -Dteamlifebind.archive.titleOnly=true'
if options_only:env['JAVA_TOOL_OPTIONS']=env.get('JAVA_TOOL_OPTIONS','')+' -Dteamlifebind.render.compat.optionsOnly=true'
if motion_only:
    env['JAVA_TOOL_OPTIONS'] = env.get('JAVA_TOOL_OPTIONS', '') + ' -Dteamlifebind.archive.motionOnly=true -Dteamlifebind.archive.motionOutput=tlb-archive-motion'
local_jdk = ROOT / ".tools/jdk26-extract/jdk-26.0.2.1+1"
if local_jdk.is_dir():
    env["JAVA_HOME"] = str(local_jdk)
env["GRADLE_USER_HOME"] = str(ROOT / ".tools/gradle-upgrade-home")
outputs = ROOT / (".tools/archive-motion-evidence" if motion_only else ".tools/archive-client-evidence")
run_root=ROOT/'.tools/archive-client-smoke'
if title_only:
    outputs=ROOT/'.tools/archive-title-evidence'
    run_root=ROOT/'.tools/archive-title-run'
if render_mode:
    outputs=ROOT/f'.tools/archive-compat-evidence/{render_mode}'
    run_root=ROOT/f'.tools/archive-compat-run/{render_mode}'
outputs.mkdir(parents=True, exist_ok=True)
digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()


def source_hashes():
    sources = [*ROOT.glob("client-ui/**/*.java"), *(p for p in ROOT.glob("client-ui/src/main/resources/**/*") if p.is_file()),
               *ROOT.glob("scripts/fixtures/aui-*.json"), *ROOT.glob("fabric/src/main/resources/assets/teamlifebind/lang/*.json"),
               ROOT / "scripts/prepare-aui.py", ROOT / "gradle/aui.gradle", ROOT / "vendor/apricityui/UPSTREAM.json"]
    sources.append(Path(__file__))
    if render_mode:
        sources.extend([ROOT/'scripts/prepare-render-compat.py',ROOT/'scripts/fixtures/render-compat-lock.json',
                        ROOT/'neoforge/src/main/java/com/teamlifebind/neoforge/mixin/SodiumLegacyExtractionMixin.java',
                        ROOT/'neoforge/src/main/resources/teamlifebind.mixins.json'])
    # This runner never enables the separate loopback fixture.
    return {p.relative_to(ROOT).as_posix(): digest(p) for p in sources if p.name != 'ArchiveE2E.java'}

for platform in platforms:
    # This options file belongs only to the isolated fixture client.
    game = run_root / f"{platform}-client"
    game.mkdir(parents=True, exist_ok=True)
    if render_mode:
        import importlib.util
        spec=importlib.util.spec_from_file_location('prepare_render_compat',ROOT/'scripts/prepare-render-compat.py')
        setup=importlib.util.module_from_spec(spec);spec.loader.exec_module(setup)
        render_mods=setup.prepare(platform,render_mode,game)
    preferences = game / 'config/teamlifebind-ui.properties'
    preferences.parent.mkdir(parents=True, exist_ok=True)
    preferences.write_text('motion=true\n', encoding='ascii')
    # Only copy the header of a world previously generated by our isolated loopback fixture.
    fixture=ROOT / f'.tools/archive-e2e/{platform}-server/archive-ui-fixture/level.dat'
    selector_world=game / 'saves/ArchiveSelectorFixture'
    if not title_only:
        if not fixture.is_file(): raise SystemExit('Generate the isolated archive-ui-fixture with test-archive-e2e.py first.')
        assert selector_world.resolve().is_relative_to(run_root.resolve()) and selector_world.name=='ArchiveSelectorFixture'
        if selector_world.exists():shutil.rmtree(selector_world)
        selector_world.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(fixture,selector_world/'level.dat')
        shutil.copytree(fixture.parent/'data/minecraft',selector_world/'data/minecraft',dirs_exist_ok=True)
    options = game / "options.txt"
    lines = options.read_text(encoding="utf-8").splitlines() if options.exists() else []
    lines = [line for line in lines if not line.startswith(("lang:", "onboardAccessibility:"))]
    options.write_text("\n".join([*lines, "lang:zh_cn", "onboardAccessibility:false"]) + "\n", encoding="utf-8")
    preferences = game / "config/teamlifebind-ui.properties"
    preferences.parent.mkdir(parents=True, exist_ok=True)
    preferences.write_text("motion=true\n", encoding="ascii")
    log = outputs / f"{platform}.log"
    started = time.time()
    tested_sources = source_hashes()
    command = [str(ROOT / ("gradlew.bat" if os.name == "nt" else "gradlew")),
               f"-Pplatforms={platform}", f"-Pdev_run_root={run_root.relative_to(ROOT).as_posix()}", "-ParchiveSelfTest",
               f":{platform}:runClient", "--console=plain"]
    if render_mode:command.extend([f'-ParchiveEvidenceRoot={outputs.relative_to(ROOT).as_posix()}',f'-PrenderCompatMode={render_mode}'])
    if title_only:command.append(f'-ParchiveEvidenceRoot={outputs.relative_to(ROOT).as_posix()}')
    command.extend(['--offline','--max-workers=1','-Dorg.gradle.parallel=false','-Dorg.gradle.jvmargs=-Xms256m -Xmx2g -XX:ActiveProcessorCount=3'])
    if platform == 'neoforge' and os.getenv('TLB_NEOFORM_CACHED') == '1':
        cache=json.loads((ROOT/'.tools/archive-neoforge-cache-evidence.json').read_text())
        artifact=ROOT/'neoforge/build/moddev/artifacts/minecraft-patched-26.3.0.71-beta-merged.jar'
        assert cache['membersIdentical'] and digest(artifact)==cache['sha256'], 'Unverified NeoForm cache'
        command.extend(['-x', ':neoforge:createMinecraftArtifacts'])
    print(f"Starting {platform} Archive interface runtime check", flush=True)
    with log.open("w", encoding="utf-8") as stream:
        run = subprocess.run(command, cwd=ROOT, env=env, stdout=stream, stderr=subprocess.STDOUT, timeout=1200)
    result = (game / 'tlb-archive-motion' if motion_only else outputs / platform) / "result.txt"
    if run.returncode or not result.exists() or result.stat().st_mtime < started:
        raise SystemExit(f"{platform}: client failed; see {log}")
    report = result.read_text(encoding="utf-8")
    if "FAIL" in report or f"PASS all {case_count} archive UI scenarios" not in report:
        raise SystemExit(report + f"\nSee {log}")
    assert "PASS SCREEN_LIQUID_MOTION" in report, 'Missing real-screen liquid transition and hovered-outline coverage'
    assert "PASS ORBITAL_BACKDROP" in report, 'Missing actual animated/static background GPU check'
    if not motion_only and not options_only and not title_only:
        assert report.count('PASS WIZARD_MOUSE ')==9, 'Missing actual mouse-driven wizard navigation and preserved name/seed coverage'
    if options_only:
        assert report.count('PASS RENDERER_OPTIONS ')==(6 if render_mode=='iris' else 3), 'Missing actual renderer options integration coverage'
    if motion_only:
        shutil.copytree(result.parent, outputs / platform, dirs_exist_ok=True)
        result = outputs / platform / 'result.txt'
    snapshots = {}
    for size in (() if motion_only else ("wide", "medium", "compact")):
        for name in kinds:
            png=result.parent/f"{size}-{name}.png"
            assert png.is_file() and png.stat().st_mtime>=started, f"Missing fresh capture: {png}"
            data=png.read_bytes()
            assert data[:8] == b"\x89PNG\r\n\x1a\n"
            snapshots[png.name] = {"sha256":digest(png),"dimensions":struct.unpack(">II", data[16:24])}
    loading_snapshots = {}
    if not motion_only and not options_only and not title_only:
        assert "PASS LOADING_GPU" in report, 'Missing real loading shader readback'
    for i in range(0 if motion_only or options_only or title_only else 17):
        png = result.parent / f'load-{i}.png'
        assert png.is_file() and png.stat().st_mtime >= started, f'Missing fresh GPU capture: {png}'
        data=png.read_bytes()
        loading_snapshots[png.name] = {"sha256":digest(png),"dimensions":struct.unpack(">II", data[16:24])}
    if tested_sources != source_hashes():
        raise SystemExit(f"{platform}: sources changed while testing; rerun before recording evidence")
    motion_snapshots = {}
    for name in ['title-hover', 'screen-old', 'screen-new', 'return-new', 'backdrop-0', 'backdrop-12', 'backdrop-still-0', 'backdrop-still-1', *[f'{direction}-wipe-{i}' for direction in ('screen','return') for i in range(3)]]:
        png = result.parent / (name + '.png')
        assert png.is_file() and png.stat().st_mtime >= started, f'Missing fresh motion capture: {png}'
        motion_snapshots[png.name] = {'sha256': digest(png)}
    evidence = {"platform": platform, "realClient": True, "worldOpened": False, "rhinoRequired": False,
                "resultSha256": digest(result), "snapshots": snapshots, "loadingSnapshots": loading_snapshots,
                "motionOnly": motion_only, "screenMotionSnapshots": motion_snapshots,
                "sources": tested_sources}
    if render_mode:evidence['renderMods']=render_mods
    (result.parent / "evidence.json").write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    assert "PASS COLD_FONT_BARRIER" in report, 'Missing cold-start CSS/font gate coverage'
    print(f"PASS {platform}: {case_count} actual-client interface scenarios", flush=True)
